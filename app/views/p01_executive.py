import pandas as pd
import plotly.express as px
import streamlit as st

from growthpulse import metrics as M, paths
from lib import data, filters, ui


def render():
    data.require_data()
    ui.header("Executive Overview", "Headline growth KPIs for the selected period, computed live from the warehouse.")
    f = filters.sidebar()
    df = filters.apply(data.perf(f.model), f)
    if df.empty:
        return ui.empty_state()
    total = M.aggregate_performance(df, window=f.window, gross_margin=f.gross_margin, data_end=f.data_end).iloc[0]
    paid = df[df.spend_usd > 0].channel_name.unique()
    paid_total = M.aggregate_performance(df[df.channel_name.isin(paid)], window=f.window, gross_margin=f.gross_margin, data_end=f.data_end).iloc[0]
    wlabel = "3-cycle" if f.window == "m3" else "12-cycle"
    ui.kpis([
        ("Media spend", ui.fmt_usd(total.spend_usd), "Platform-reported spend in the period"),
        ("New paying customers", ui.fmt_num(total.new_customers), "All channels incl. organic, credited by the chosen attribution model"),
        ("Paid-media CAC", ui.fmt_usd(paid_total.cac), "Media spend / customers credited to paid channels"),
        (f"ROAS ({wlabel})", ui.fmt_num(paid_total.roas_window, 2), "Net revenue from first billing cycles per $ of spend, on fully observed cohorts. Not profit; not proof of incrementality."),
        ("LTV:CAC", ui.fmt_num(paid_total.ltv_cac_window, 2), f"Gross-profit per customer over the {wlabel} window / paid-media CAC (window LTV, not lifetime)."),
        ("Net revenue to date", ui.fmt_usd(total.net_revenue_to_date), "All net revenue so far from customers acquired in the period"),
    ])
    m = df.assign(month=df.metric_date.dt.to_period("M").dt.to_timestamp())
    monthly = m.groupby("month").agg(spend=("spend_usd", "sum"), customers=("new_customers", "sum"), signups=("signups", "sum")).reset_index()
    pm = m[m.channel_name.isin(paid)].groupby("month").agg(p_spend=("spend_usd", "sum"), p_cust=("new_customers", "sum")).reset_index()
    pm["cac"] = M.safe_divide(pm.p_spend, pm.p_cust)
    c1, c2 = st.columns(2)
    with c1:
        fig = px.bar(monthly, x="month", y=["spend"], title="Monthly media spend (USD)", labels={"value": "USD", "month": ""})
        fig.add_scatter(x=monthly.month, y=monthly.customers, name="New customers", yaxis="y2", mode="lines+markers")
        fig.update_layout(yaxis2=dict(overlaying="y", side="right", title="customers"), legend_title="", margin=dict(t=50))
        st.plotly_chart(fig, width="stretch")
    with c2:
        fig = px.line(pm, x="month", y="cac", markers=True, title="Paid-media CAC by acquisition month (USD)", labels={"cac": "USD", "month": ""})
        st.plotly_chart(fig, width="stretch")
        st.caption("Spend and the customers it produces are separated by trial + journey lag (weeks), so single-month CAC is noisy; read the trend.")
    st.subheader("What the analysis recommends")
    recs = data.table(paths.ANALYTICS, "recommendations")
    if recs.empty:
        ui.empty_state("No recommendations table found.", "Run the pipeline.")
    else:
        st.dataframe(recs[["channel", "recommended_action", "evidence", "caveats"]], width="stretch", hide_index=True)
        st.caption("Generated by rules applied to calculated results (see the report and Methodology page for thresholds). Recommendations are hypotheses to test, not instructions.")
    ui.download(monthly, "executive_monthly_summary")
