#!/usr/bin/env python
"""Regenerate docs/data_dictionary.md from the raw schema + the dbt manifest (descriptions and grains live in the dbt YAML)."""
import json, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from growthpulse.datagen import schema

L = ["# Data dictionary\n", "_Auto-generated by `python scripts/build_docs.py`. All raw tables are **SYNTHETIC**._\n",
     "Conventions: UTC timestamps, USD currency, flags are 0/1 integers, IDs are strings, dates are calendar dates.\n",
     "## 1. Raw tables (synthetic source data)\n"]
for t, spec in schema.TABLES.items():
    L += [f"### `raw.{t}`\n", f"**Grain:** {spec['grain']}\n", "| Column | Type | Description |", "|---|---|---|"]
    L += [f"| `{c}` | {ty} | {d} |" for c, ty, d in spec["columns"]]
    L.append("")
man = ROOT / "dbt_project" / "target" / "manifest.json"
L.append("## 2. Warehouse models (dbt)\n")
if man.exists():
    m = json.loads(man.read_text())
    layers = {"staging": [], "intermediate": [], "marts": []}
    for n in m["nodes"].values():
        if n["resource_type"] == "model":
            for k in layers:
                if f"/models/{k}/" in "/" + n["original_file_path"].replace("\\", "/"):
                    layers[k].append(n)
    for k, nodes in layers.items():
        L.append(f"### {k.title()} layer\n")
        L += ["| Model | Description / grain | Materialisation | Depends on |", "|---|---|---|---|"]
        for n in sorted(nodes, key=lambda x: x["name"]):
            deps = ", ".join(sorted(d.split(".")[-1] for d in n["depends_on"]["nodes"]))
            first_sql = next((ln.strip("- ").strip() for ln in n["raw_code"].splitlines() if ln.strip().startswith("--")), "")
            desc = (n.get("description") or first_sql).replace("\n", " ").replace("|", "/")
            L.append(f"| `{n['name']}` | {desc} | {n['config']['materialized']} | {deps} |")
        L.append("")
else:
    L.append("_Run `dbt docs generate` (inside dbt_project/) or the pipeline first, then re-run this script to list the models._\n")
(ROOT / "docs" / "data_dictionary.md").write_text("\n".join(L))
print("wrote docs/data_dictionary.md")
